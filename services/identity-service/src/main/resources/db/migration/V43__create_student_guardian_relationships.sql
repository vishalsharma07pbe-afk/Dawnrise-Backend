INSERT INTO role_permissions (
    role,
    permission_id
)
SELECT
    roles.role,
    permissions.id
FROM (
         VALUES
             ('ADMIN'),
             ('PRINCIPAL'),
             ('VICE_PRINCIPAL'),
             ('ADMISSIONS_OFFICER')
     ) AS roles(role)
         CROSS JOIN permissions
WHERE permissions.code IN (
    'STUDENT_GUARDIAN_RELATIONSHIP_VIEW',
    'STUDENT_GUARDIAN_RELATIONSHIP_MANAGE'
)
ON CONFLICT (role, permission_id) DO NOTHING;
