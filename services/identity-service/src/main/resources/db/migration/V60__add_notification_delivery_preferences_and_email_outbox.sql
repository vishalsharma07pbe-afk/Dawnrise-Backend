CREATE TABLE notification_email_outbox (
    id UUID PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    event_id UUID NOT NULL,
    recipient_id UUID NOT NULL,
    user_id BIGINT NOT NULL,
    destination_email VARCHAR(254) NOT NULL CHECK (BTRIM(destination_email)<>''),
    template_key VARCHAR(60) NOT NULL CHECK (BTRIM(template_key)<>''),
    subject VARCHAR(160) NOT NULL CHECK (BTRIM(subject)<>'' AND subject !~ '[<>]'),
    template_variables JSONB NOT NULL CHECK (JSONB_TYPEOF(template_variables)='object'),
    action_type VARCHAR(40) NOT NULL,
    action_reference_id BIGINT,
    delivery_mode VARCHAR(12) NOT NULL CHECK (delivery_mode IN ('IMMEDIATE','DIGEST')),
    message_id VARCHAR(200) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','SENT','CANCELLED','DEAD_LETTER')),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count>=0),
    available_at TIMESTAMPTZ NOT NULL,
    lease_owner UUID,
    lease_until TIMESTAMPTZ,
    sent_at TIMESTAMPTZ,
    dead_lettered_at TIMESTAMPTZ,
    last_error VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_notification_email_event_user UNIQUE(event_id,user_id),
    CONSTRAINT uk_notification_email_message_id UNIQUE(message_id),
    CONSTRAINT fk_notification_email_event FOREIGN KEY(event_id,organization_id)
        REFERENCES notification_events(id,organization_id) ON DELETE CASCADE,
    CONSTRAINT fk_notification_email_recipient FOREIGN KEY(recipient_id)
        REFERENCES notification_recipients(id) ON DELETE CASCADE,
    CONSTRAINT fk_notification_email_user FOREIGN KEY(user_id,organization_id)
        REFERENCES users(id,organization_id) ON DELETE CASCADE,
    CONSTRAINT chk_notification_email_lease CHECK ((lease_owner IS NULL)=(lease_until IS NULL))
);

CREATE TABLE notification_email_delivery_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL CHECK (organization_id>0),
    outbox_id UUID NOT NULL,
    action VARCHAR(30) NOT NULL CHECK (action='DEAD_LETTER_REQUEUED'),
    actor_user_id BIGINT NOT NULL CHECK (actor_user_id>0),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_notification_email_claim ON notification_email_outbox(status,available_at,lease_until,id)
    WHERE status='PENDING';
CREATE INDEX idx_notification_email_dead_letter ON notification_email_outbox(organization_id,dead_lettered_at DESC,id)
    WHERE status='DEAD_LETTER';
CREATE INDEX idx_notification_email_digest ON notification_email_outbox(user_id,available_at,id)
    WHERE status='PENDING' AND delivery_mode='DIGEST';
