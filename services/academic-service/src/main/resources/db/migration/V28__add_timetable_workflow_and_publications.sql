CREATE TABLE timetable_workflow_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    academic_year_id BIGINT NOT NULL CHECK (academic_year_id > 0),
    draft_id BIGINT NOT NULL CHECK (draft_id > 0),
    from_status VARCHAR(20) NOT NULL,
    to_status VARCHAR(20) NOT NULL,
    reason VARCHAR(1000),
    actor_user_id BIGINT NOT NULL CHECK (actor_user_id > 0),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_timetable_workflow_transition CHECK (
       (from_status='DRAFT' AND to_status='IN_REVIEW' AND reason IS NULL) OR
       (from_status='IN_REVIEW' AND to_status='DRAFT' AND BTRIM(reason)<>'') OR
       (from_status='IN_REVIEW' AND to_status='APPROVED' AND reason IS NULL) OR
       (from_status='APPROVED' AND to_status='DRAFT' AND BTRIM(reason)<>'') OR
       (from_status='APPROVED' AND to_status='PUBLISHED' AND reason IS NULL)),
    CONSTRAINT fk_timetable_workflow_draft FOREIGN KEY (draft_id,organization_id,academic_year_id)
        REFERENCES timetable_drafts(id,organization_id,academic_year_id) ON DELETE CASCADE
);

CREATE TABLE timetable_publications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    academic_year_id BIGINT NOT NULL CHECK (academic_year_id > 0),
    source_draft_id BIGINT NOT NULL CHECK (source_draft_id > 0),
    publication_number BIGINT NOT NULL CHECK (publication_number > 0),
    effective_from DATE NOT NULL,
    effective_to_exclusive DATE,
    published_by_user_id BIGINT NOT NULL CHECK (published_by_user_id > 0),
    published_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_timetable_publication_range CHECK
        (effective_to_exclusive IS NULL OR effective_to_exclusive > effective_from),
    CONSTRAINT uk_timetable_publication_scope UNIQUE (id,organization_id,academic_year_id),
    CONSTRAINT uk_timetable_publication_number UNIQUE
        (organization_id,academic_year_id,publication_number),
    CONSTRAINT uk_timetable_publication_draft UNIQUE
        (organization_id,academic_year_id,source_draft_id),
    CONSTRAINT fk_timetable_publication_year FOREIGN KEY (academic_year_id,organization_id)
        REFERENCES academic_years(id,organization_id) ON DELETE RESTRICT,
    CONSTRAINT fk_timetable_publication_draft FOREIGN KEY (source_draft_id,organization_id,academic_year_id)
        REFERENCES timetable_drafts(id,organization_id,academic_year_id) ON DELETE RESTRICT,
    CONSTRAINT ex_timetable_publication_effective_range EXCLUDE USING gist (
        organization_id WITH =, academic_year_id WITH =,
        daterange(effective_from,COALESCE(effective_to_exclusive,'infinity'::date),'[)') WITH &&)
);

CREATE TABLE timetable_publication_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    academic_year_id BIGINT NOT NULL CHECK (academic_year_id > 0),
    publication_id BIGINT NOT NULL CHECK (publication_id > 0),
    grade_level_id BIGINT NOT NULL CHECK (grade_level_id > 0),
    grade_name VARCHAR(100) NOT NULL,
    section_id BIGINT NOT NULL CHECK (section_id > 0),
    section_name VARCHAR(100) NOT NULL,
    wing_id BIGINT NOT NULL CHECK (wing_id > 0),
    wing_name VARCHAR(120) NOT NULL,
    bell_schedule_interval_id BIGINT NOT NULL CHECK (bell_schedule_interval_id > 0),
    day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    interval_type VARCHAR(30) NOT NULL CHECK (interval_type IN
        ('TEACHING','ASSEMBLY','SUPERVISED_ACTIVITY','RECESS','TRANSITION','FIXED_NON_STUDENT')),
    activity_name VARCHAR(120) NOT NULL CHECK (BTRIM(activity_name)<>''),
    grade_level_subject_id BIGINT,
    subject_name VARCHAR(120),
    teacher_user_id BIGINT CHECK (teacher_user_id IS NULL OR teacher_user_id > 0),
    room_id BIGINT CHECK (room_id IS NULL OR room_id > 0),
    room_name VARCHAR(120),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_timetable_publication_entry UNIQUE
        (organization_id,academic_year_id,publication_id,section_id,day_of_week,bell_schedule_interval_id),
    CONSTRAINT chk_timetable_publication_entry_times CHECK
        (end_time>start_time AND EXTRACT(SECOND FROM start_time)=0 AND EXTRACT(SECOND FROM end_time)=0),
    CONSTRAINT fk_timetable_publication_entry_publication
        FOREIGN KEY (publication_id,organization_id,academic_year_id)
        REFERENCES timetable_publications(id,organization_id,academic_year_id) ON DELETE RESTRICT
);

CREATE INDEX idx_timetable_publication_entry_school
    ON timetable_publication_entries(organization_id,academic_year_id,publication_id,day_of_week,start_time);
CREATE INDEX idx_timetable_publication_entry_teacher
    ON timetable_publication_entries(organization_id,academic_year_id,publication_id,teacher_user_id,day_of_week,start_time);
CREATE INDEX idx_timetable_workflow_event_draft
    ON timetable_workflow_events(organization_id,academic_year_id,draft_id,occurred_at DESC);

CREATE FUNCTION reject_timetable_publication_entry_mutation() RETURNS TRIGGER
LANGUAGE plpgsql AS $$ BEGIN
    RAISE EXCEPTION USING ERRCODE='55000', MESSAGE='Published timetable entries are immutable snapshots';
END $$;
CREATE TRIGGER trg_timetable_publication_entry_immutable
BEFORE UPDATE OR DELETE ON timetable_publication_entries
FOR EACH ROW EXECUTE FUNCTION reject_timetable_publication_entry_mutation();
