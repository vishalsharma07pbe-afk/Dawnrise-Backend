CREATE TABLE timetable_generation_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    academic_year_id BIGINT NOT NULL CHECK (academic_year_id > 0),
    request_key VARCHAR(80) NOT NULL CHECK (BTRIM(request_key) <> ''),
    status VARCHAR(24) NOT NULL CHECK (status IN ('QUEUED','RUNNING','COMPLETED','FAILED','CANCEL_REQUESTED','CANCELLED')),
    proposal_count INTEGER NOT NULL CHECK (proposal_count BETWEEN 1 AND 5),
    completed_proposals INTEGER NOT NULL DEFAULT 0 CHECK (completed_proposals >= 0),
    seed BIGINT NOT NULL,
    solve_time_seconds INTEGER NOT NULL CHECK (solve_time_seconds BETWEEN 1 AND 300),
    source_draft_id BIGINT,
    prefer_class_teacher_first BOOLEAN NOT NULL DEFAULT FALSE,
    cancel_requested BOOLEAN NOT NULL DEFAULT FALSE,
    failure_message VARCHAR(500),
    created_by_user_id BIGINT NOT NULL CHECK (created_by_user_id > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT uk_timetable_generation_job_scope UNIQUE (id, organization_id, academic_year_id),
    CONSTRAINT uk_timetable_generation_request UNIQUE (organization_id, academic_year_id, request_key),
    CONSTRAINT fk_timetable_generation_year FOREIGN KEY (academic_year_id, organization_id)
        REFERENCES academic_years (id, organization_id) ON DELETE CASCADE,
    CONSTRAINT fk_timetable_generation_source_draft FOREIGN KEY (source_draft_id, organization_id, academic_year_id)
        REFERENCES timetable_drafts (id, organization_id, academic_year_id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uk_timetable_generation_active_year
    ON timetable_generation_jobs (organization_id, academic_year_id)
    WHERE status IN ('QUEUED','RUNNING','CANCEL_REQUESTED');

CREATE TABLE timetable_generation_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    academic_year_id BIGINT NOT NULL CHECK (academic_year_id > 0),
    job_id BIGINT NOT NULL CHECK (job_id > 0),
    proposal_index INTEGER NOT NULL CHECK (proposal_index > 0),
    draft_id BIGINT,
    feasible BOOLEAN NOT NULL,
    hard_score BIGINT NOT NULL,
    soft_score BIGINT NOT NULL,
    score_breakdown JSONB NOT NULL DEFAULT '{}'::jsonb,
    validation_findings JSONB NOT NULL DEFAULT '[]'::jsonb,
    unmet_requirements JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_timetable_generation_proposal UNIQUE (organization_id, academic_year_id, job_id, proposal_index),
    CONSTRAINT fk_timetable_generation_proposal_job FOREIGN KEY (job_id, organization_id, academic_year_id)
        REFERENCES timetable_generation_jobs (id, organization_id, academic_year_id) ON DELETE CASCADE,
    CONSTRAINT fk_timetable_generation_proposal_draft FOREIGN KEY (draft_id, organization_id, academic_year_id)
        REFERENCES timetable_drafts (id, organization_id, academic_year_id) ON DELETE SET NULL (draft_id)
);

CREATE INDEX idx_timetable_generation_jobs_tenant
    ON timetable_generation_jobs (organization_id, academic_year_id, created_at DESC);
