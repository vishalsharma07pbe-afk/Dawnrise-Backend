CREATE TABLE grading_policies (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL,
 academic_year_id BIGINT NOT NULL, grade_level_id BIGINT NOT NULL, name VARCHAR(120) NOT NULL,
 notes VARCHAR(500), status VARCHAR(20) NOT NULL DEFAULT 'DRAFT', subject_pass_percentage NUMERIC(9,6) NOT NULL,
 overall_pass_percentage NUMERIC(9,6) NOT NULL, absent_counts_as_failure BOOLEAN NOT NULL,
 require_every_subject_to_pass BOOLEAN NOT NULL, decimal_scale INTEGER NOT NULL, rounding_mode VARCHAR(30) NOT NULL,
 policy_version INTEGER NOT NULL DEFAULT 0, version BIGINT NOT NULL DEFAULT 0,
 created_by_user_id BIGINT NOT NULL, updated_by_user_id BIGINT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_gp_year FOREIGN KEY (academic_year_id,organization_id) REFERENCES academic_years(id,organization_id),
 CONSTRAINT fk_gp_grade FOREIGN KEY (grade_level_id,academic_year_id,organization_id) REFERENCES grade_levels(id,academic_year_id,organization_id),
 CONSTRAINT chk_gp_status CHECK(status IN ('DRAFT','ACTIVE','RETIRED')),
 CONSTRAINT chk_gp_percent CHECK(subject_pass_percentage BETWEEN 0 AND 100 AND overall_pass_percentage BETWEEN 0 AND 100),
 CONSTRAINT chk_gp_scale CHECK(decimal_scale BETWEEN 0 AND 6),
 CONSTRAINT chk_gp_ids CHECK(organization_id>0 AND academic_year_id>0 AND grade_level_id>0 AND created_by_user_id>0 AND updated_by_user_id>0),
 CONSTRAINT chk_gp_version CHECK(policy_version>=0 AND version>=0 AND (status='DRAFT' OR policy_version>0)),
 CONSTRAINT chk_gp_rounding CHECK(rounding_mode IN ('UP','DOWN','CEILING','FLOOR','HALF_UP','HALF_DOWN','HALF_EVEN')),
 CONSTRAINT chk_gp_names CHECK(length(trim(name))>0),
 CONSTRAINT chk_gp_timestamps CHECK(updated_at>=created_at),
 CONSTRAINT uk_gp_id_scope UNIQUE(id,organization_id),
 CONSTRAINT uk_gp_hierarchy_scope UNIQUE(id,organization_id,academic_year_id,grade_level_id)
);
CREATE UNIQUE INDEX uk_gp_active_scope ON grading_policies(organization_id,academic_year_id,grade_level_id) WHERE status='ACTIVE';

CREATE TABLE grading_policy_bands (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, policy_id BIGINT NOT NULL, organization_id BIGINT NOT NULL,
 label VARCHAR(30) NOT NULL, minimum_percentage NUMERIC(9,6) NOT NULL, maximum_percentage NUMERIC(9,6) NOT NULL,
 display_order INTEGER NOT NULL, description VARCHAR(250),
 CONSTRAINT fk_gpb_policy FOREIGN KEY(policy_id,organization_id) REFERENCES grading_policies(id,organization_id) ON DELETE CASCADE,
 CONSTRAINT chk_gpb_range CHECK(minimum_percentage BETWEEN 0 AND 100 AND maximum_percentage BETWEEN 0 AND 100 AND minimum_percentage<=maximum_percentage),
 CONSTRAINT chk_gpb_ids CHECK(policy_id>0 AND organization_id>0 AND display_order>0),
 CONSTRAINT chk_gpb_label CHECK(length(trim(label))>0),
 CONSTRAINT uk_gpb_label UNIQUE(policy_id,label), CONSTRAINT uk_gpb_order UNIQUE(policy_id,display_order)
);

CREATE TABLE report_cards (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL, publication_id BIGINT NOT NULL,
 academic_year_id BIGINT NOT NULL, examination_id BIGINT NOT NULL, grade_level_id BIGINT NOT NULL, section_id BIGINT NOT NULL,
 student_user_id BIGINT NOT NULL, enrollment_id BIGINT NOT NULL, grading_policy_id BIGINT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'DRAFT', academic_year_name VARCHAR(50) NOT NULL, examination_name VARCHAR(120) NOT NULL,
 grade_name VARCHAR(100) NOT NULL, section_name VARCHAR(100) NOT NULL, roll_number VARCHAR(30) NOT NULL,
 result_published_at TIMESTAMPTZ NOT NULL, policy_name VARCHAR(120) NOT NULL, policy_version INTEGER NOT NULL,
 subject_pass_percentage NUMERIC(9,6) NOT NULL, overall_pass_percentage NUMERIC(9,6) NOT NULL,
 absent_counts_as_failure BOOLEAN NOT NULL, require_every_subject_to_pass BOOLEAN NOT NULL,
 decimal_scale INTEGER NOT NULL, rounding_mode VARCHAR(30) NOT NULL, total_maximum_marks NUMERIC(12,2) NOT NULL,
 total_obtained_marks NUMERIC(12,2) NOT NULL, aggregate_percentage NUMERIC(9,6) NOT NULL,
 overall_grade VARCHAR(30) NOT NULL, passed BOOLEAN NOT NULL, absent_subject_count INTEGER NOT NULL,
 partial BOOLEAN NOT NULL, return_reason VARCHAR(500), version BIGINT NOT NULL DEFAULT 0,
 created_by_user_id BIGINT NOT NULL, reviewed_by_user_id BIGINT, published_by_user_id BIGINT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 published_at TIMESTAMPTZ,
 CONSTRAINT fk_rc_publication FOREIGN KEY(publication_id,organization_id,academic_year_id,examination_id,grade_level_id,section_id)
 REFERENCES result_publications(id,organization_id,academic_year_id,examination_id,grade_level_id,section_id),
 CONSTRAINT fk_rc_policy FOREIGN KEY(grading_policy_id,organization_id,academic_year_id,grade_level_id) REFERENCES grading_policies(id,organization_id,academic_year_id,grade_level_id),
 CONSTRAINT fk_rc_enrollment FOREIGN KEY(enrollment_id,organization_id) REFERENCES student_enrollments(id,organization_id) ON DELETE RESTRICT,
 CONSTRAINT chk_rc_status CHECK(status IN ('DRAFT','IN_REVIEW','APPROVED','PUBLISHED')),
 CONSTRAINT chk_rc_ids CHECK(organization_id>0 AND publication_id>0 AND academic_year_id>0 AND examination_id>0 AND grade_level_id>0 AND section_id>0 AND student_user_id>0 AND enrollment_id>0 AND grading_policy_id>0 AND created_by_user_id>0),
 CONSTRAINT chk_rc_percent CHECK(subject_pass_percentage BETWEEN 0 AND 100 AND overall_pass_percentage BETWEEN 0 AND 100 AND aggregate_percentage BETWEEN 0 AND 100),
 CONSTRAINT chk_rc_totals CHECK(total_maximum_marks>0 AND total_obtained_marks>=0 AND total_obtained_marks<=total_maximum_marks AND absent_subject_count>=0),
 CONSTRAINT chk_rc_version CHECK(policy_version>0 AND version>=0 AND decimal_scale BETWEEN 0 AND 6),
 CONSTRAINT chk_rc_names CHECK(length(trim(academic_year_name))>0 AND length(trim(examination_name))>0 AND length(trim(grade_name))>0 AND length(trim(section_name))>0 AND length(trim(roll_number))>0 AND length(trim(policy_name))>0 AND length(trim(overall_grade))>0),
 CONSTRAINT chk_rc_actor_ids CHECK((reviewed_by_user_id IS NULL OR reviewed_by_user_id>0) AND (published_by_user_id IS NULL OR published_by_user_id>0)),
 CONSTRAINT chk_rc_rounding CHECK(rounding_mode IN ('UP','DOWN','CEILING','FLOOR','HALF_UP','HALF_DOWN','HALF_EVEN')),
 CONSTRAINT chk_rc_publication_state CHECK((status='PUBLISHED' AND published_at IS NOT NULL AND published_by_user_id>0) OR (status<>'PUBLISHED' AND published_at IS NULL AND published_by_user_id IS NULL)),
 CONSTRAINT chk_rc_review_state CHECK(status NOT IN ('APPROVED','PUBLISHED') OR reviewed_by_user_id>0),
 CONSTRAINT chk_rc_return_reason CHECK((return_reason IS NULL OR length(trim(return_reason))>0) AND (return_reason IS NULL OR status='DRAFT')),
 CONSTRAINT chk_rc_timestamps CHECK(updated_at>=created_at AND result_published_at<=created_at AND (published_at IS NULL OR published_at>=created_at)),
 CONSTRAINT uk_rc_publication_student UNIQUE(organization_id,publication_id,student_user_id),
 CONSTRAINT uk_rc_id_scope UNIQUE(id,organization_id)
);
CREATE INDEX idx_rc_student ON report_cards(organization_id,student_user_id,status,published_at DESC);

CREATE TABLE report_card_subjects (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, report_card_id BIGINT NOT NULL, organization_id BIGINT NOT NULL,
 subject_id BIGINT NOT NULL, subject_code VARCHAR(50) NOT NULL, subject_name VARCHAR(150) NOT NULL,
 maximum_marks NUMERIC(7,2) NOT NULL, obtained_marks NUMERIC(7,2), absent BOOLEAN NOT NULL,
 percentage NUMERIC(9,6), grade_label VARCHAR(30), passed BOOLEAN NOT NULL, display_order INTEGER NOT NULL,
 CONSTRAINT fk_rcs_card FOREIGN KEY(report_card_id,organization_id) REFERENCES report_cards(id,organization_id) ON DELETE CASCADE,
 CONSTRAINT chk_rcs_ids CHECK(report_card_id>0 AND organization_id>0 AND subject_id>0 AND display_order>0),
 CONSTRAINT chk_rcs_max CHECK(maximum_marks>0 AND (obtained_marks IS NULL OR (obtained_marks>=0 AND obtained_marks<=maximum_marks)) AND (percentage IS NULL OR percentage BETWEEN 0 AND 100)),
 CONSTRAINT chk_rcs_absence CHECK((absent AND obtained_marks IS NULL AND percentage IS NULL) OR (NOT absent AND obtained_marks IS NOT NULL AND percentage IS NOT NULL)),
 CONSTRAINT chk_rcs_names CHECK(length(trim(subject_code))>0 AND length(trim(subject_name))>0 AND (grade_label IS NULL OR length(trim(grade_label))>0)),
 CONSTRAINT uk_rcs_subject UNIQUE(report_card_id,subject_id),
 CONSTRAINT uk_rcs_order UNIQUE(report_card_id,display_order)
);
