CREATE TABLE timetable_teacher_absences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    academic_year_id BIGINT NOT NULL CHECK (academic_year_id > 0),
    teacher_user_id BIGINT NOT NULL CHECK (teacher_user_id > 0),
    teacher_display_name VARCHAR(200) NOT NULL CHECK (BTRIM(teacher_display_name) <> ''),
    absence_date DATE NOT NULL,
    start_time TIME,
    end_time TIME,
    start_minute INTEGER GENERATED ALWAYS AS
        (COALESCE(EXTRACT(HOUR FROM start_time)::INTEGER * 60 + EXTRACT(MINUTE FROM start_time)::INTEGER, 0)) STORED,
    end_minute INTEGER GENERATED ALWAYS AS
        (COALESCE(EXTRACT(HOUR FROM end_time)::INTEGER * 60 + EXTRACT(MINUTE FROM end_time)::INTEGER, 1440)) STORED,
    absence_type VARCHAR(30) NOT NULL CHECK
        (absence_type IN ('KNOWN_LEAVE','UNEXPECTED_ABSENCE','LATE_ARRIVAL','EARLY_DEPARTURE')),
    status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED' CHECK (status IN ('CONFIRMED','CANCELLED')),
    source VARCHAR(30) NOT NULL DEFAULT 'EXPLICIT_CONFIRMED' CHECK
        (source IN ('EXPLICIT_CONFIRMED','AUTHORITATIVE_LEAVE')),
    reason VARCHAR(1000) NOT NULL CHECK (BTRIM(reason) <> ''),
    idempotency_key VARCHAR(200) NOT NULL CHECK (BTRIM(idempotency_key) <> ''),
    request_fingerprint VARCHAR(128) NOT NULL CHECK (BTRIM(request_fingerprint) <> ''),
    recorded_by_user_id BIGINT NOT NULL CHECK (recorded_by_user_id > 0),
    cancelled_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_timetable_teacher_absence_times CHECK
        ((start_time IS NULL AND end_time IS NULL) OR
         (start_time IS NOT NULL AND end_time IS NOT NULL AND end_time > start_time)),
    CONSTRAINT chk_timetable_teacher_absence_cancelled CHECK
        ((status='CANCELLED' AND cancelled_at IS NOT NULL) OR
         (status='CONFIRMED' AND cancelled_at IS NULL)),
    CONSTRAINT uk_timetable_teacher_absence_context UNIQUE
        (id, organization_id, academic_year_id),
    CONSTRAINT uk_timetable_teacher_absence_idempotency UNIQUE (organization_id, idempotency_key),
    CONSTRAINT fk_timetable_teacher_absence_year FOREIGN KEY (academic_year_id, organization_id)
        REFERENCES academic_years(id, organization_id) ON DELETE RESTRICT,
    CONSTRAINT ex_timetable_teacher_absence_overlap EXCLUDE USING gist
        (organization_id WITH =, teacher_user_id WITH =, absence_date WITH =,
         int4range(start_minute,end_minute,'[)') WITH &&) WHERE (status='CONFIRMED')
);

