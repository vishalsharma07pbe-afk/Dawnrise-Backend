        FOREIGN KEY (absence_id, organization_id, academic_year_id)
        REFERENCES timetable_teacher_absences(id, organization_id, academic_year_id) ON DELETE RESTRICT
);

CREATE TABLE timetable_daily_cover_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    academic_year_id BIGINT NOT NULL CHECK (academic_year_id > 0),
    case_id BIGINT NOT NULL CHECK (case_id > 0),
    cover_date DATE NOT NULL,
    section_id BIGINT NOT NULL CHECK (section_id > 0),
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    start_minute INTEGER GENERATED ALWAYS AS
        (EXTRACT(HOUR FROM start_time)::INTEGER * 60 + EXTRACT(MINUTE FROM start_time)::INTEGER) STORED,
    end_minute INTEGER GENERATED ALWAYS AS
        (EXTRACT(HOUR FROM end_time)::INTEGER * 60 + EXTRACT(MINUTE FROM end_time)::INTEGER) STORED,
    mode VARCHAR(20) NOT NULL CHECK (mode IN ('MANUAL','AUTONOMOUS')),
    arrangement_type VARCHAR(30) NOT NULL CHECK
        (arrangement_type IN ('TEACHER_COVER','ALTERNATIVE_ACTIVITY')),
    status VARCHAR(30) NOT NULL CHECK
        (status IN ('AWAITING_APPROVAL','APPROVED','REJECTED','CANCELLED','SUPERSEDED','CORRECTED')),
    cover_teacher_user_id BIGINT,
    cover_teacher_display_name VARCHAR(200),
    activity_plan_id BIGINT,
    activity_name VARCHAR(120),
    supervisor_user_id BIGINT,
    supervisor_display_name VARCHAR(200),
    resource_teacher_user_id BIGINT GENERATED ALWAYS AS
        (COALESCE(cover_teacher_user_id, supervisor_user_id)) STORED,
    room_id BIGINT,
    room_name VARCHAR(120),
    room_exclusive BOOLEAN NOT NULL DEFAULT FALSE,
    rank INTEGER NOT NULL CHECK (rank BETWEEN 1 AND 5),
    reason VARCHAR(1000) NOT NULL CHECK (BTRIM(reason) <> ''),
    request_key VARCHAR(200) NOT NULL CHECK (BTRIM(request_key) <> ''),
    decision_request_key VARCHAR(200),
    proposed_by_user_id BIGINT NOT NULL CHECK (proposed_by_user_id > 0),
    approved_by_user_id BIGINT,
    approved_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_timetable_daily_cover_proposal_times CHECK (end_time > start_time),
    CONSTRAINT chk_timetable_daily_cover_arrangement CHECK
        ((arrangement_type='TEACHER_COVER' AND cover_teacher_user_id IS NOT NULL
          AND activity_plan_id IS NULL AND supervisor_user_id IS NULL) OR
         (arrangement_type='ALTERNATIVE_ACTIVITY' AND cover_teacher_user_id IS NULL
          AND activity_plan_id IS NOT NULL AND supervisor_user_id IS NOT NULL)),
    CONSTRAINT chk_timetable_daily_cover_approval CHECK
        ((status='APPROVED' AND approved_by_user_id IS NOT NULL AND approved_at IS NOT NULL) OR
         (status<>'APPROVED' AND approved_at IS NULL)),
    CONSTRAINT fk_timetable_daily_cover_proposal_case
        FOREIGN KEY (case_id, organization_id, academic_year_id)
        REFERENCES timetable_daily_cover_cases(id, organization_id, academic_year_id) ON DELETE RESTRICT,
    CONSTRAINT fk_timetable_daily_cover_proposal_activity
        FOREIGN KEY (activity_plan_id, organization_id)
        REFERENCES timetable_cover_activity_plans(id, organization_id) ON DELETE RESTRICT,
    CONSTRAINT uk_timetable_daily_cover_proposal_request UNIQUE (organization_id, request_key),
    CONSTRAINT uk_timetable_daily_cover_proposal_decision UNIQUE (organization_id, decision_request_key),
    CONSTRAINT ex_timetable_daily_cover_teacher_overlap EXCLUDE USING gist
        (organization_id WITH =, cover_date WITH =, resource_teacher_user_id WITH =,
         int4range(start_minute,end_minute,'[)') WITH &&)
        WHERE (status IN ('AWAITING_APPROVAL','APPROVED')),
    CONSTRAINT ex_timetable_daily_cover_room_overlap EXCLUDE USING gist
        (organization_id WITH =, cover_date WITH =, room_id WITH =,
         int4range(start_minute,end_minute,'[)') WITH &&)
        WHERE (status IN ('AWAITING_APPROVAL','APPROVED') AND room_exclusive),
    CONSTRAINT ex_timetable_daily_cover_section_overlap EXCLUDE USING gist
        (organization_id WITH =, cover_date WITH =, section_id WITH =,
         int4range(start_minute,end_minute,'[)') WITH &&)
        WHERE (status IN ('AWAITING_APPROVAL','APPROVED'))
);

CREATE UNIQUE INDEX uk_timetable_daily_cover_active_proposal
    ON timetable_daily_cover_proposals(organization_id, case_id)
    WHERE status IN ('AWAITING_APPROVAL','APPROVED');

CREATE TABLE timetable_daily_cover_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    academic_year_id BIGINT NOT NULL CHECK (academic_year_id > 0),
    absence_id BIGINT,
    case_id BIGINT,
    proposal_id BIGINT,
    event_type VARCHAR(40) NOT NULL CHECK (event_type IN
        ('ABSENCE_RECORDED','ABSENCE_CORRECTED','ABSENCE_CANCELLED','CASE_CREATED',
         'PROPOSAL_CREATED','PROPOSAL_APPROVED','PROPOSAL_REJECTED','COVER_CHANGED',
         'COVER_CANCELLED','ELAPSED_COVER_CORRECTED','CLASS_UNCOVERED')),
    reason VARCHAR(1000),
    actor_user_id BIGINT NOT NULL CHECK (actor_user_id > 0),
    detail_json JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (JSONB_TYPEOF(detail_json)='object'),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE timetable_daily_cover_notification_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    case_id BIGINT,
    event_type VARCHAR(40) NOT NULL CHECK (event_type IN
        ('COVER_NEEDED','APPROVAL_REQUIRED','IMMINENT_UNCOVERED','CLASS_UNCOVERED','COVER_CHANGED')),
    idempotency_key VARCHAR(200) NOT NULL,
    payload JSONB NOT NULL CHECK (JSONB_TYPEOF(payload)='object'),
    publication_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK
        (publication_status IN ('PENDING','PUBLISHED','DEAD_LETTER')),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    available_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMPTZ,
    last_error VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_timetable_daily_cover_outbox_idempotency UNIQUE (organization_id, idempotency_key),
    CONSTRAINT fk_timetable_daily_cover_outbox_case FOREIGN KEY (case_id, organization_id)
        REFERENCES timetable_daily_cover_cases(id, organization_id) ON DELETE RESTRICT
);

CREATE INDEX idx_timetable_daily_cover_case_day
    ON timetable_daily_cover_cases(organization_id, academic_year_id, cover_date, wing_id, start_time);
CREATE INDEX idx_timetable_daily_cover_proposal_case
    ON timetable_daily_cover_proposals(organization_id, case_id, created_at DESC);
CREATE INDEX idx_timetable_daily_cover_event_case
    ON timetable_daily_cover_events(organization_id, case_id, occurred_at, id);
CREATE INDEX idx_timetable_daily_cover_outbox_pending
    ON timetable_daily_cover_notification_outbox(publication_status, available_at, id)
    WHERE publication_status='PENDING';
