    academic_year_id BIGINT NOT NULL CHECK (academic_year_id > 0),
    cover_date DATE NOT NULL,
    publication_id BIGINT NOT NULL CHECK (publication_id > 0),
    publication_entry_id BIGINT NOT NULL CHECK (publication_entry_id > 0),
    absence_id BIGINT NOT NULL CHECK (absence_id > 0),
    section_id BIGINT NOT NULL CHECK (section_id > 0),
    section_name VARCHAR(100) NOT NULL,
    wing_id BIGINT NOT NULL CHECK (wing_id > 0),
    wing_name VARCHAR(120) NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    interval_type VARCHAR(30) NOT NULL,
    original_activity_name VARCHAR(120) NOT NULL,
    original_grade_level_subject_id BIGINT,
    original_subject_name VARCHAR(120),
    original_teacher_user_id BIGINT NOT NULL CHECK (original_teacher_user_id > 0),
    original_teacher_display_name VARCHAR(200) NOT NULL,
    original_room_id BIGINT,
    original_room_name VARCHAR(120),
    status VARCHAR(30) NOT NULL DEFAULT 'COVER_NEEDED' CHECK
        (status IN ('COVER_NEEDED','AWAITING_APPROVAL','COVERED','UNCOVERED','CANCELLED','CORRECTED')),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
