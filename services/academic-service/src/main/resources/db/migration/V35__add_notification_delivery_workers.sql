-- Reliable academic notification delivery, publication events, and operational coverage incidents.

ALTER TABLE student_attendance_notification_outbox
    ADD COLUMN lease_owner UUID,
    ADD COLUMN lease_until TIMESTAMPTZ,
    ADD COLUMN recipient_user_ids BIGINT[],
    ADD COLUMN dead_lettered_at TIMESTAMPTZ;

ALTER TABLE student_attendance_notification_outbox
    ADD CONSTRAINT chk_student_attendance_notification_outbox_lease
        CHECK ((lease_owner IS NULL) = (lease_until IS NULL)),
    ADD CONSTRAINT chk_student_attendance_notification_outbox_recipients
        CHECK (recipient_user_ids IS NULL OR
               (CARDINALITY(recipient_user_ids) > 0 AND 0 < ALL(recipient_user_ids)));

ALTER TABLE timetable_daily_cover_notification_outbox
    ADD COLUMN lease_owner UUID,
    ADD COLUMN lease_until TIMESTAMPTZ,
    ADD COLUMN recipient_user_ids BIGINT[],
    ADD COLUMN dead_lettered_at TIMESTAMPTZ,
    ADD COLUMN updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;

ALTER TABLE timetable_daily_cover_notification_outbox
    DROP CONSTRAINT timetable_daily_cover_notification_outbox_event_type_check,
    ADD CONSTRAINT chk_timetable_daily_cover_outbox_event_type CHECK (event_type IN
        ('COVER_NEEDED','APPROVAL_REQUIRED','CONFIRMED_SUBSTITUTION',
         'IMMINENT_UNCOVERED','CLASS_UNCOVERED','COVER_CHANGED')),
    ADD CONSTRAINT chk_timetable_daily_cover_outbox_lease
        CHECK ((lease_owner IS NULL) = (lease_until IS NULL)),
    ADD CONSTRAINT chk_timetable_daily_cover_outbox_recipients
        CHECK (recipient_user_ids IS NULL OR
               (CARDINALITY(recipient_user_ids) > 0 AND 0 < ALL(recipient_user_ids)));

CREATE TABLE academic_publication_notification_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    academic_year_id BIGINT NOT NULL CHECK (academic_year_id > 0),
    student_user_id BIGINT NOT NULL CHECK (student_user_id > 0),
    artifact_id BIGINT NOT NULL CHECK (artifact_id > 0),
    event_type VARCHAR(30) NOT NULL CHECK
        (event_type IN ('RESULT_PUBLISHED','REPORT_CARD_PUBLISHED')),
    idempotency_key VARCHAR(200) NOT NULL CHECK (BTRIM(idempotency_key) <> ''),
    payload JSONB NOT NULL CHECK (JSONB_TYPEOF(payload)='object'),
    recipient_user_ids BIGINT[],
    publication_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK
        (publication_status IN ('PENDING','PUBLISHED','DEAD_LETTER')),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    available_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lease_owner UUID,
    lease_until TIMESTAMPTZ,
    published_at TIMESTAMPTZ,
    dead_lettered_at TIMESTAMPTZ,
    last_error VARCHAR(1000),
    occurred_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_academic_publication_notification_idempotency
        UNIQUE (organization_id,idempotency_key),
    CONSTRAINT chk_academic_publication_notification_lease
        CHECK ((lease_owner IS NULL) = (lease_until IS NULL)),
    CONSTRAINT chk_academic_publication_notification_recipients
        CHECK (recipient_user_ids IS NULL OR
               (CARDINALITY(recipient_user_ids) > 0 AND 0 < ALL(recipient_user_ids)))
);

CREATE TABLE timetable_daily_cover_incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    case_id BIGINT NOT NULL CHECK (case_id > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','RESOLVED')),
    first_alert_at TIMESTAMPTZ NOT NULL,
    next_escalation_at TIMESTAMPTZ,
    escalation_level INTEGER NOT NULL DEFAULT 0 CHECK (escalation_level BETWEEN 0 AND 2),
    acknowledged_at TIMESTAMPTZ,
    acknowledged_by_user_id BIGINT,
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT uk_timetable_daily_cover_incident_case UNIQUE (organization_id,case_id),
    CONSTRAINT uk_timetable_daily_cover_incident_context UNIQUE (id,organization_id),
    CONSTRAINT fk_timetable_daily_cover_incident_case FOREIGN KEY (case_id,organization_id)
        REFERENCES timetable_daily_cover_cases(id,organization_id) ON DELETE RESTRICT,
    CONSTRAINT chk_timetable_daily_cover_incident_ack CHECK
        ((acknowledged_at IS NULL) = (acknowledged_by_user_id IS NULL)),
    CONSTRAINT chk_timetable_daily_cover_incident_resolution CHECK
        ((status='OPEN' AND resolved_at IS NULL) OR (status='RESOLVED' AND resolved_at IS NOT NULL))
);

CREATE TABLE academic_notification_delivery_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    source VARCHAR(30) NOT NULL CHECK (source IN ('ATTENDANCE','DAILY_COVER','PUBLICATION')),
    outbox_id BIGINT NOT NULL CHECK (outbox_id > 0),
    action VARCHAR(30) NOT NULL CHECK (action='DEAD_LETTER_REQUEUED'),
    actor_user_id BIGINT NOT NULL CHECK (actor_user_id > 0),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_student_attendance_notification_claim
    ON student_attendance_notification_outbox(publication_status,available_at,lease_until,id)
    WHERE publication_status='PENDING';
CREATE INDEX idx_timetable_daily_cover_notification_claim
    ON timetable_daily_cover_notification_outbox(publication_status,available_at,lease_until,id)
    WHERE publication_status='PENDING';
CREATE INDEX idx_academic_publication_notification_claim
    ON academic_publication_notification_outbox(publication_status,available_at,lease_until,id)
    WHERE publication_status='PENDING';
CREATE INDEX idx_academic_publication_notification_dead_letter
    ON academic_publication_notification_outbox(organization_id,dead_lettered_at DESC,id)
    WHERE publication_status='DEAD_LETTER';
CREATE INDEX idx_timetable_daily_cover_incident_escalation
    ON timetable_daily_cover_incidents(status,next_escalation_at,id)
    WHERE status='OPEN' AND acknowledged_at IS NULL;
CREATE INDEX idx_academic_notification_delivery_audit_org
    ON academic_notification_delivery_audit(organization_id,occurred_at DESC,id DESC);
