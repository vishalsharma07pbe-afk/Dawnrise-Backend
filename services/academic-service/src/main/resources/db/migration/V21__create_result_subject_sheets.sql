CREATE TABLE result_subject_sheets
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id         BIGINT       NOT NULL,
    academic_year_id        BIGINT       NOT NULL,
    examination_id          BIGINT       NOT NULL,
    scheduled_assessment_id BIGINT       NOT NULL,
    grade_level_id          BIGINT       NOT NULL,
    section_id              BIGINT       NOT NULL,
    grade_level_subject_id  BIGINT       NOT NULL,
    status                  VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    submitted_by_user_id    BIGINT,
    submitted_at            TIMESTAMP WITH TIME ZONE,
    reviewed_by_user_id     BIGINT,
    reviewed_at             TIMESTAMP WITH TIME ZONE,
    review_note             VARCHAR(500),
    version                 BIGINT       NOT NULL DEFAULT 0,
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_result_sheet_organization_positive CHECK (organization_id > 0),
    CONSTRAINT chk_result_sheet_year_positive CHECK (academic_year_id > 0),
    CONSTRAINT chk_result_sheet_exam_positive CHECK (examination_id > 0),
    CONSTRAINT chk_result_sheet_assessment_positive CHECK (scheduled_assessment_id > 0),
    CONSTRAINT chk_result_sheet_grade_positive CHECK (grade_level_id > 0),
    CONSTRAINT chk_result_sheet_section_positive CHECK (section_id > 0),
    CONSTRAINT chk_result_sheet_subject_positive CHECK (grade_level_subject_id > 0),
    CONSTRAINT chk_result_sheet_status
        CHECK (status IN ('DRAFT', 'SUBMITTED', 'RETURNED', 'APPROVED')),
    CONSTRAINT chk_result_sheet_submitted_actor
        CHECK (
            (status IN ('DRAFT', 'RETURNED') AND submitted_by_user_id IS NULL AND submitted_at IS NULL)
            OR
            (status IN ('SUBMITTED', 'APPROVED') AND submitted_by_user_id IS NOT NULL AND submitted_at IS NOT NULL)
        ),
    CONSTRAINT chk_result_sheet_review_actor
        CHECK (
            (status IN ('DRAFT', 'SUBMITTED') AND reviewed_by_user_id IS NULL AND reviewed_at IS NULL)
            OR
            (status IN ('RETURNED', 'APPROVED') AND reviewed_by_user_id IS NOT NULL AND reviewed_at IS NOT NULL)
        ),
    CONSTRAINT chk_result_sheet_review_note_not_blank
        CHECK (review_note IS NULL OR BTRIM(review_note) <> ''),
    CONSTRAINT uk_result_sheet_assessment_section
        UNIQUE (scheduled_assessment_id, section_id),
    CONSTRAINT uk_result_sheet_id_scope
        UNIQUE (id, organization_id, academic_year_id, grade_level_id, section_id),
    CONSTRAINT fk_result_sheet_assessment
        FOREIGN KEY (
            scheduled_assessment_id,
            examination_id,
            grade_level_id,
            grade_level_subject_id,
            academic_year_id,
            organization_id
        )
            REFERENCES scheduled_assessments (
                id,
                examination_id,
                grade_level_id,
                grade_level_subject_id,
                academic_year_id,
                organization_id
            )
            ON DELETE RESTRICT,
    CONSTRAINT fk_result_sheet_section
        FOREIGN KEY (
            section_id,
            grade_level_id,
            academic_year_id,
            organization_id
        )
            REFERENCES sections (
                id,
                grade_level_id,
                academic_year_id,
                organization_id
            )
            ON DELETE RESTRICT
);

CREATE TABLE result_subject_marks
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id       BIGINT       NOT NULL,
    academic_year_id      BIGINT       NOT NULL,
    grade_level_id        BIGINT       NOT NULL,
    section_id            BIGINT       NOT NULL,
    subject_sheet_id      BIGINT       NOT NULL,
    student_enrollment_id BIGINT       NOT NULL,
    student_user_id       BIGINT       NOT NULL,
    roll_number_snapshot  VARCHAR(30)  NOT NULL,
    absent                BOOLEAN      NOT NULL DEFAULT FALSE,
    marks_obtained        NUMERIC(7, 2),
    version               BIGINT       NOT NULL DEFAULT 0,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_result_mark_organization_positive CHECK (organization_id > 0),
    CONSTRAINT chk_result_mark_year_positive CHECK (academic_year_id > 0),
    CONSTRAINT chk_result_mark_grade_positive CHECK (grade_level_id > 0),
    CONSTRAINT chk_result_mark_section_positive CHECK (section_id > 0),
    CONSTRAINT chk_result_mark_sheet_positive CHECK (subject_sheet_id > 0),
    CONSTRAINT chk_result_mark_enrollment_positive CHECK (student_enrollment_id > 0),
    CONSTRAINT chk_result_mark_student_positive CHECK (student_user_id > 0),
    CONSTRAINT chk_result_mark_roll_not_blank CHECK (BTRIM(roll_number_snapshot) <> ''),
    CONSTRAINT chk_result_mark_absent_marks
        CHECK (
            (absent = TRUE AND marks_obtained IS NULL)
            OR
            (absent = FALSE AND (marks_obtained IS NULL OR marks_obtained >= 0))
        ),
    CONSTRAINT uk_result_mark_sheet_enrollment
        UNIQUE (subject_sheet_id, student_enrollment_id),
    CONSTRAINT fk_result_mark_sheet
        FOREIGN KEY (
            subject_sheet_id,
            organization_id,
            academic_year_id,
            grade_level_id,
            section_id
        )
            REFERENCES result_subject_sheets (
                id,
                organization_id,
                academic_year_id,
                grade_level_id,
                section_id
            )
            ON DELETE RESTRICT,
    CONSTRAINT fk_result_mark_enrollment
        FOREIGN KEY (
            student_enrollment_id,
            section_id,
            grade_level_id,
            academic_year_id,
            organization_id
        )
            REFERENCES student_enrollments (
                id,
                section_id,
                grade_level_id,
                academic_year_id,
                organization_id
            )
            ON DELETE RESTRICT
);

CREATE INDEX idx_result_sheet_scope_status
    ON result_subject_sheets (
        organization_id,
        academic_year_id,
        examination_id,
        grade_level_id,
        section_id,
        status
    );

CREATE INDEX idx_result_mark_sheet_order
    ON result_subject_marks (
        subject_sheet_id,
        roll_number_snapshot,
        id
    );
