CREATE TABLE result_publications
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id      BIGINT NOT NULL,
    academic_year_id     BIGINT NOT NULL,
    examination_id       BIGINT NOT NULL,
    grade_level_id       BIGINT NOT NULL,
    section_id           BIGINT NOT NULL,
    status               VARCHAR(20) NOT NULL DEFAULT 'PUBLISHED',
    published_by_user_id BIGINT NOT NULL,
    published_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    version              BIGINT NOT NULL DEFAULT 0,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_result_publication_organization_positive CHECK (organization_id > 0),
    CONSTRAINT chk_result_publication_year_positive CHECK (academic_year_id > 0),
    CONSTRAINT chk_result_publication_exam_positive CHECK (examination_id > 0),
    CONSTRAINT chk_result_publication_grade_positive CHECK (grade_level_id > 0),
    CONSTRAINT chk_result_publication_section_positive CHECK (section_id > 0),
    CONSTRAINT chk_result_publication_actor_positive CHECK (published_by_user_id > 0),
    CONSTRAINT chk_result_publication_status CHECK (status IN ('PUBLISHED', 'WITHDRAWN')),
    CONSTRAINT uk_result_publication_scope
        UNIQUE (organization_id, academic_year_id, examination_id, grade_level_id, section_id),
    CONSTRAINT uk_result_publication_id_scope
        UNIQUE (id, organization_id, academic_year_id, examination_id, grade_level_id, section_id),
    CONSTRAINT fk_result_publication_year
        FOREIGN KEY (academic_year_id, organization_id)
            REFERENCES academic_years (id, organization_id) ON DELETE RESTRICT,
    CONSTRAINT fk_result_publication_examination
        FOREIGN KEY (examination_id, academic_year_id, organization_id)
            REFERENCES examinations (id, academic_year_id, organization_id) ON DELETE RESTRICT,
    CONSTRAINT fk_result_publication_grade
        FOREIGN KEY (grade_level_id, academic_year_id, organization_id)
            REFERENCES grade_levels (id, academic_year_id, organization_id) ON DELETE RESTRICT,
    CONSTRAINT fk_result_publication_section
        FOREIGN KEY (section_id, grade_level_id, academic_year_id, organization_id)
            REFERENCES sections (id, grade_level_id, academic_year_id, organization_id) ON DELETE RESTRICT
);

CREATE INDEX idx_result_publication_student_scope
    ON result_publications (organization_id, academic_year_id, grade_level_id, section_id, published_at DESC);
