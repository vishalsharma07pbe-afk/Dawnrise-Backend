CREATE TABLE timetable_expiry_notification_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    academic_year_id BIGINT NOT NULL CHECK (academic_year_id > 0),
    publication_id BIGINT NOT NULL CHECK (publication_id > 0),
    event_type VARCHAR(30) NOT NULL CHECK
        (event_type IN ('TIMETABLE_PUBLISHED','TIMETABLE_CHANGED',
                        'TIMETABLE_EXPIRING','TIMETABLE_EXPIRES_TODAY')),
    idempotency_key VARCHAR(200) NOT NULL CHECK (BTRIM(idempotency_key) <> ''),
    payload JSONB NOT NULL CHECK (JSONB_TYPEOF(payload)='object'),
    recipient_user_ids BIGINT[],
    publication_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK
        (publication_status IN ('PENDING','PUBLISHED','DEAD_LETTER')),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    available_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lease_owner UUID,
    lease_until TIMESTAMPTZ,
    published_at TIMESTAMPTZ,
    dead_lettered_at TIMESTAMPTZ,
    last_error VARCHAR(1000),
    occurred_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_timetable_expiry_notification_idempotency
        UNIQUE (organization_id,idempotency_key),
    CONSTRAINT fk_timetable_expiry_notification_publication
        FOREIGN KEY (publication_id,organization_id,academic_year_id)
        REFERENCES timetable_publications(id,organization_id,academic_year_id) ON DELETE RESTRICT,
    CONSTRAINT chk_timetable_expiry_notification_lease
        CHECK ((lease_owner IS NULL) = (lease_until IS NULL)),
    CONSTRAINT chk_timetable_expiry_notification_recipients
        CHECK (recipient_user_ids IS NULL OR
               (CARDINALITY(recipient_user_ids) > 0 AND 0 < ALL(recipient_user_ids)))
);

CREATE INDEX idx_timetable_expiry_notification_claim
    ON timetable_expiry_notification_outbox(publication_status,available_at,lease_until,id)
    WHERE publication_status='PENDING';

CREATE TABLE examination_notification_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    academic_year_id BIGINT NOT NULL CHECK (academic_year_id > 0),
    examination_id BIGINT NOT NULL CHECK (examination_id > 0),
    actor_user_id BIGINT NOT NULL CHECK (actor_user_id > 0),
    event_type VARCHAR(40) NOT NULL CHECK (event_type='EXAM_SCHEDULE_PUBLISHED'),
    idempotency_key VARCHAR(200) NOT NULL CHECK (BTRIM(idempotency_key)<>''),
    payload JSONB NOT NULL CHECK (JSONB_TYPEOF(payload)='object'),
    recipient_user_ids BIGINT[],
    publication_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK
        (publication_status IN ('PENDING','PUBLISHED','DEAD_LETTER')),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count>=0),
    available_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lease_owner UUID,
    lease_until TIMESTAMPTZ,
    published_at TIMESTAMPTZ,
    dead_lettered_at TIMESTAMPTZ,
    last_error VARCHAR(1000),
    occurred_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_examination_notification_idempotency UNIQUE(organization_id,idempotency_key),
    CONSTRAINT fk_examination_notification_exam FOREIGN KEY
        (examination_id,academic_year_id,organization_id)
        REFERENCES examinations(id,academic_year_id,organization_id) ON DELETE RESTRICT,
    CONSTRAINT chk_examination_notification_lease CHECK
        ((lease_owner IS NULL)=(lease_until IS NULL)),
    CONSTRAINT chk_examination_notification_recipients CHECK
        (recipient_user_ids IS NULL OR (CARDINALITY(recipient_user_ids)>0 AND 0<ALL(recipient_user_ids)))
);
CREATE INDEX idx_examination_notification_claim
    ON examination_notification_outbox(publication_status,available_at,lease_until,id)
    WHERE publication_status='PENDING';

