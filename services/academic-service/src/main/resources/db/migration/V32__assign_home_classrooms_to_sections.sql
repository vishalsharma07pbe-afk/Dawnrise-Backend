ALTER TABLE sections
    ADD CONSTRAINT uk_section_id_year_org UNIQUE (id, academic_year_id, organization_id);

CREATE TABLE timetable_section_home_rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    academic_year_id BIGINT NOT NULL CHECK (academic_year_id > 0),
    section_id BIGINT NOT NULL CHECK (section_id > 0),
    room_id BIGINT NOT NULL CHECK (room_id > 0),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_timetable_section_home_room UNIQUE (organization_id, academic_year_id, section_id),
    CONSTRAINT uk_timetable_home_room_per_year UNIQUE (organization_id, academic_year_id, room_id),
    CONSTRAINT uk_timetable_home_room_section UNIQUE (id, organization_id),
    CONSTRAINT fk_timetable_home_room_section FOREIGN KEY (section_id, academic_year_id, organization_id)
        REFERENCES sections (id, academic_year_id, organization_id) ON DELETE CASCADE,
    CONSTRAINT fk_timetable_home_room_room FOREIGN KEY (room_id, organization_id)
        REFERENCES timetable_rooms (id, organization_id) ON DELETE RESTRICT
);

CREATE INDEX idx_timetable_section_home_rooms_room
    ON timetable_section_home_rooms (organization_id, room_id);
