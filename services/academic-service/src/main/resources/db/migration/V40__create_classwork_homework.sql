CREATE TABLE learning_posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    academic_year_id BIGINT NOT NULL,
    grade_level_id BIGINT NOT NULL,
    section_id BIGINT NOT NULL,
    grade_level_subject_id BIGINT NOT NULL,
    teacher_user_id BIGINT NOT NULL,
    post_type VARCHAR(20) NOT NULL CHECK (post_type IN ('CLASSWORK','HOMEWORK')),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED','WITHDRAWN')),
    title VARCHAR(200) NOT NULL,
    instructions TEXT,
    lesson_date DATE,
    topics TEXT,
    pages_exercises TEXT,
    recap TEXT,
    due_at TIMESTAMP WITH TIME ZONE,
    related_classwork_id BIGINT,
    points INTEGER NOT NULL DEFAULT 0 CHECK (points >= 0),
    version BIGINT NOT NULL DEFAULT 0,
    published_at TIMESTAMP WITH TIME ZONE,
    withdrawn_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_learning_post_assignment FOREIGN KEY
      (section_id, grade_level_id, academic_year_id, organization_id)
      REFERENCES sections(id, grade_level_id, academic_year_id, organization_id),
    CONSTRAINT fk_learning_post_subject FOREIGN KEY
      (grade_level_subject_id, grade_level_id, academic_year_id, organization_id)
      REFERENCES grade_level_subjects(id, grade_level_id, academic_year_id, organization_id),
    CONSTRAINT fk_learning_post_related FOREIGN KEY (related_classwork_id) REFERENCES learning_posts(id),
    CONSTRAINT chk_learning_post_fields CHECK (
      (post_type='CLASSWORK' AND lesson_date IS NOT NULL AND due_at IS NULL)
      OR (post_type='HOMEWORK' AND due_at IS NOT NULL)
    )
);
CREATE INDEX idx_learning_posts_audience ON learning_posts(organization_id,academic_year_id,section_id,status);
CREATE INDEX idx_learning_posts_teacher ON learning_posts(organization_id,teacher_user_id,updated_at DESC);

CREATE TABLE learning_tasks (
    id UUID PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    post_id BIGINT NOT NULL REFERENCES learning_posts(id) ON DELETE CASCADE,
    display_order INTEGER NOT NULL CHECK(display_order > 0),
    description TEXT NOT NULL,
    reference_type VARCHAR(30),
    reference_value TEXT,
    content_revision INTEGER NOT NULL DEFAULT 1,
    UNIQUE(post_id,display_order), UNIQUE(post_id,id)
);

CREATE TABLE learning_links (
    id UUID PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    post_id BIGINT NOT NULL REFERENCES learning_posts(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    url TEXT NOT NULL CHECK(url ~ '^https://'),
    link_kind VARCHAR(20) NOT NULL CHECK(link_kind IN ('REQUIRED','EXTRA_HELP')),
    video_start_seconds INTEGER CHECK(video_start_seconds IS NULL OR video_start_seconds >= 0),
    display_order INTEGER NOT NULL,
    UNIQUE(post_id,display_order)
);

CREATE TABLE learning_attachments (
    id UUID PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    post_id BIGINT NOT NULL REFERENCES learning_posts(id) ON DELETE CASCADE,
    task_id UUID,
    original_name VARCHAR(200) NOT NULL,
    content_type VARCHAR(80) NOT NULL CHECK(content_type IN ('image/jpeg','image/png','image/webp')),
    byte_size BIGINT NOT NULL CHECK(byte_size BETWEEN 1 AND 10485760),
    sha256 CHAR(64) NOT NULL,
    content BYTEA NOT NULL,
    uploaded_by_user_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(post_id,task_id) REFERENCES learning_tasks(post_id,id) ON DELETE CASCADE
);

CREATE TABLE learning_student_progress (
    organization_id BIGINT NOT NULL,
    post_id BIGINT NOT NULL REFERENCES learning_posts(id) ON DELETE CASCADE,
    student_user_id BIGINT NOT NULL,
    task_id UUID NOT NULL,
    task_revision INTEGER NOT NULL,
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    completed_at TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY(organization_id,post_id,student_user_id,task_id),
    FOREIGN KEY(post_id,task_id) REFERENCES learning_tasks(post_id,id) ON DELETE CASCADE
);

CREATE TABLE learning_reviews (
    organization_id BIGINT NOT NULL,
    post_id BIGINT NOT NULL REFERENCES learning_posts(id) ON DELETE CASCADE,
    student_user_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL CHECK(status IN ('IN_PROGRESS','READY_FOR_REVIEW','VERIFIED','CHANGES_REQUESTED')),
    submitted_at TIMESTAMP WITH TIME ZONE,
    reviewed_by_user_id BIGINT,
    reviewed_at TIMESTAMP WITH TIME ZONE,
    feedback TEXT,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY(organization_id,post_id,student_user_id)
);

CREATE TABLE student_points_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    academic_year_id BIGINT NOT NULL,
    recipient_user_id BIGINT NOT NULL,
    source_type VARCHAR(50) NOT NULL,
    source_id VARCHAR(100) NOT NULL,
    amount INTEGER NOT NULL CHECK(amount <> 0),
    issuer_user_id BIGINT NOT NULL,
    reason VARCHAR(500),
    adjustment_of_id BIGINT REFERENCES student_points_ledger(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_learning_points_award ON student_points_ledger(organization_id,recipient_user_id,source_type,source_id) WHERE adjustment_of_id IS NULL;
CREATE INDEX idx_student_points_history ON student_points_ledger(organization_id,academic_year_id,recipient_user_id,created_at DESC);

CREATE TABLE learning_notification_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE,
    organization_id BIGINT NOT NULL,
    post_id BIGINT NOT NULL REFERENCES learning_posts(id),
    event_type VARCHAR(40) NOT NULL,
    recipient_user_ids BIGINT[],
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    idempotency_key VARCHAR(200) NOT NULL,
    publication_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempt_count INTEGER NOT NULL DEFAULT 0,
    available_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lease_owner UUID,
    lease_until TIMESTAMP WITH TIME ZONE,
    last_error TEXT,
    published_at TIMESTAMP WITH TIME ZONE,
    dead_lettered_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(organization_id,idempotency_key)
);
