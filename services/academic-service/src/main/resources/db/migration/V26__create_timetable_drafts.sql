CREATE FUNCTION validate_timetable_draft_slot_snapshot() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE configured RECORD;
DECLARE room_record RECORD;
BEGIN
    SELECT i.interval_type, i.start_time, i.end_time, d.day_of_week, a.wing_id
      INTO configured
      FROM timetable_bell_intervals i
      JOIN timetable_bell_schedule_days d ON d.id=i.bell_schedule_day_id AND d.organization_id=i.organization_id
      JOIN timetable_bell_schedule_assignments a ON a.bell_schedule_id=d.bell_schedule_id
       AND a.organization_id=i.organization_id AND a.academic_year_id=NEW.academic_year_id
      JOIN timetable_grade_wings gw ON gw.organization_id=a.organization_id
       AND gw.academic_year_id=a.academic_year_id AND gw.grade_level_id=NEW.grade_level_id
       AND gw.wing_id=a.wing_id
     WHERE i.id=NEW.bell_schedule_interval_id AND i.organization_id=NEW.organization_id
       AND a.wing_id=NEW.wing_id AND (a.grade_level_id=NEW.grade_level_id OR
           (a.grade_level_id IS NULL AND NOT EXISTS (
               SELECT 1 FROM timetable_bell_schedule_assignments override_assignment
               WHERE override_assignment.organization_id=a.organization_id
                 AND override_assignment.academic_year_id=a.academic_year_id
                 AND override_assignment.grade_level_id=NEW.grade_level_id)))
     ORDER BY a.grade_level_id NULLS LAST LIMIT 1;
    IF NOT FOUND OR configured.interval_type NOT IN ('TEACHING','SUPERVISED_ACTIVITY')
       OR configured.interval_type <> NEW.activity_type
       OR configured.day_of_week <> NEW.day_of_week OR configured.start_time <> NEW.start_time
       OR configured.end_time <> NEW.end_time THEN
        RAISE EXCEPTION USING ERRCODE='23514', CONSTRAINT='chk_timetable_draft_slot_resolved_interval',
            MESSAGE='Draft slot must match the grade resolved bell interval';
    END IF;
    IF NEW.room_id IS NOT NULL THEN
        SELECT exclusive_use INTO room_record FROM timetable_rooms
         WHERE id=NEW.room_id AND organization_id=NEW.organization_id AND active;
        IF NOT FOUND OR room_record.exclusive_use <> NEW.room_exclusive THEN
            RAISE EXCEPTION USING ERRCODE='23514', CONSTRAINT='chk_timetable_draft_slot_room_snapshot',
                MESSAGE='Draft slot room snapshot must match an active room';
        END IF;
    END IF;
    RETURN NEW;
END $$;

CREATE CONSTRAINT TRIGGER trg_timetable_draft_slot_snapshot
AFTER INSERT OR UPDATE ON timetable_draft_section_slots
DEFERRABLE INITIALLY IMMEDIATE
FOR EACH ROW EXECUTE FUNCTION validate_timetable_draft_slot_snapshot();
