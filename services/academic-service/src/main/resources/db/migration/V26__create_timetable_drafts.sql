CREATE TABLE timetable_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    academic_year_id BIGINT NOT NULL CHECK (academic_year_id > 0),
    name VARCHAR(120) NOT NULL CHECK (BTRIM(name) <> ''),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_by_user_id BIGINT NOT NULL CHECK (created_by_user_id > 0),
    updated_by_user_id BIGINT NOT NULL CHECK (updated_by_user_id > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_timetable_draft_id_org_year UNIQUE (id, organization_id, academic_year_id),
    CONSTRAINT uk_timetable_draft_name UNIQUE (organization_id, academic_year_id, name),
    CONSTRAINT fk_timetable_draft_year FOREIGN KEY (academic_year_id, organization_id)
        REFERENCES academic_years (id, organization_id) ON DELETE CASCADE
);

CREATE TABLE timetable_draft_section_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    academic_year_id BIGINT NOT NULL CHECK (academic_year_id > 0),
    draft_id BIGINT NOT NULL CHECK (draft_id > 0),
    grade_level_id BIGINT NOT NULL CHECK (grade_level_id > 0),
    section_id BIGINT NOT NULL CHECK (section_id > 0),
    wing_id BIGINT NOT NULL CHECK (wing_id > 0),
    bell_schedule_interval_id BIGINT NOT NULL CHECK (bell_schedule_interval_id > 0),
    day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    activity_type VARCHAR(30) NOT NULL CHECK (activity_type IN ('TEACHING','SUPERVISED_ACTIVITY')),
    activity_name VARCHAR(120) NOT NULL CHECK (BTRIM(activity_name) <> ''),
    grade_level_subject_id BIGINT,
    teacher_user_id BIGINT CHECK (teacher_user_id IS NULL OR teacher_user_id > 0),
    room_id BIGINT,
    room_exclusive BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    start_minute INTEGER GENERATED ALWAYS AS ((EXTRACT(HOUR FROM start_time)::INTEGER * 60) + EXTRACT(MINUTE FROM start_time)::INTEGER) STORED,
    end_minute INTEGER GENERATED ALWAYS AS ((EXTRACT(HOUR FROM end_time)::INTEGER * 60) + EXTRACT(MINUTE FROM end_time)::INTEGER) STORED,
    CONSTRAINT uk_timetable_draft_slot_id_scope UNIQUE (id, organization_id, academic_year_id, draft_id),
    CONSTRAINT uk_timetable_draft_section_interval UNIQUE
        (organization_id, academic_year_id, draft_id, section_id, day_of_week, bell_schedule_interval_id)
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT chk_timetable_draft_slot_times CHECK (end_time > start_time),
    CONSTRAINT chk_timetable_draft_slot_minute_granularity CHECK (
        EXTRACT(SECOND FROM start_time) = 0 AND EXTRACT(SECOND FROM end_time) = 0
    ),
    CONSTRAINT chk_timetable_draft_slot_subject CHECK (
        (activity_type = 'TEACHING' AND grade_level_subject_id IS NOT NULL)
        OR (activity_type = 'SUPERVISED_ACTIVITY' AND grade_level_subject_id IS NULL)
    ),
    CONSTRAINT chk_timetable_draft_slot_room CHECK (
        (room_id IS NULL AND NOT room_exclusive) OR room_id > 0
    ),
    CONSTRAINT fk_timetable_draft_slot_draft FOREIGN KEY (draft_id, organization_id, academic_year_id)
        REFERENCES timetable_drafts (id, organization_id, academic_year_id) ON DELETE CASCADE,
    CONSTRAINT fk_timetable_draft_slot_section FOREIGN KEY (section_id, grade_level_id, academic_year_id, organization_id)
        REFERENCES sections (id, grade_level_id, academic_year_id, organization_id) ON DELETE CASCADE,
    CONSTRAINT fk_timetable_draft_slot_wing FOREIGN KEY (wing_id, organization_id)
        REFERENCES timetable_wings (id, organization_id) ON DELETE RESTRICT,
    CONSTRAINT fk_timetable_draft_slot_interval FOREIGN KEY (bell_schedule_interval_id, organization_id)
        REFERENCES timetable_bell_intervals (id, organization_id) ON DELETE RESTRICT,
    CONSTRAINT fk_timetable_draft_slot_subject FOREIGN KEY (grade_level_subject_id, grade_level_id, academic_year_id, organization_id)
        REFERENCES grade_level_subjects (id, grade_level_id, academic_year_id, organization_id) ON DELETE RESTRICT,
    CONSTRAINT fk_timetable_draft_slot_room FOREIGN KEY (room_id, organization_id)
        REFERENCES timetable_rooms (id, organization_id) ON DELETE RESTRICT,
    CONSTRAINT ex_timetable_draft_section_overlap EXCLUDE USING gist (
        organization_id WITH =, academic_year_id WITH =, draft_id WITH =,
        section_id WITH =, day_of_week WITH =,
        int4range(start_minute, end_minute, '[)') WITH &&
    ) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT ex_timetable_draft_teacher_overlap EXCLUDE USING gist (
        organization_id WITH =, academic_year_id WITH =, draft_id WITH =,
        teacher_user_id WITH =, day_of_week WITH =,
        int4range(start_minute, end_minute, '[)') WITH &&
    ) WHERE (teacher_user_id IS NOT NULL) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT ex_timetable_draft_exclusive_room_overlap EXCLUDE USING gist (
        organization_id WITH =, academic_year_id WITH =, draft_id WITH =,
        room_id WITH =, day_of_week WITH =,
        int4range(start_minute, end_minute, '[)') WITH &&
    ) WHERE (room_id IS NOT NULL AND room_exclusive) DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE timetable_draft_slot_pins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    academic_year_id BIGINT NOT NULL CHECK (academic_year_id > 0),
    draft_id BIGINT NOT NULL CHECK (draft_id > 0),
    slot_id BIGINT NOT NULL CHECK (slot_id > 0),
    pinned_by_user_id BIGINT NOT NULL CHECK (pinned_by_user_id > 0),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_timetable_draft_slot_pin UNIQUE (organization_id, academic_year_id, draft_id, slot_id),
    CONSTRAINT fk_timetable_draft_slot_pin FOREIGN KEY (slot_id, organization_id, academic_year_id, draft_id)
        REFERENCES timetable_draft_section_slots (id, organization_id, academic_year_id, draft_id) ON DELETE CASCADE
);

CREATE TABLE timetable_draft_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    academic_year_id BIGINT NOT NULL CHECK (academic_year_id > 0),
    draft_id BIGINT NOT NULL CHECK (draft_id > 0),
    actor_user_id BIGINT NOT NULL CHECK (actor_user_id > 0),
    action VARCHAR(40) NOT NULL CHECK (action IN ('CREATE_DRAFT','ADD','MOVE','SWAP','REMOVE','PIN','UNPIN')),
    slot_id BIGINT,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_timetable_draft_audit_draft FOREIGN KEY (draft_id, organization_id, academic_year_id)
        REFERENCES timetable_drafts (id, organization_id, academic_year_id) ON DELETE CASCADE
);

CREATE INDEX idx_timetable_draft_slots_school_view
