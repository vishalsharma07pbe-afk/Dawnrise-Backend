-- Deployment prerequisite: the migration role must be allowed to install btree_gist,
-- or a database administrator must install it before this migration runs.  The DO
-- block turns a missing package or insufficient privilege into an actionable error.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_available_extensions WHERE name = 'btree_gist') THEN
        RAISE EXCEPTION 'Timetable migration requires the PostgreSQL btree_gist extension package';
    END IF;
    BEGIN
        CREATE EXTENSION IF NOT EXISTS btree_gist;
    EXCEPTION WHEN insufficient_privilege THEN
        RAISE EXCEPTION 'Timetable migration requires btree_gist; install it as a database administrator or grant the migration role CREATE on the database';
    END;
END $$;

