CREATE FUNCTION validate_timetable_schedule_assignment_wing() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.grade_level_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM timetable_grade_wings gw
        WHERE gw.organization_id = NEW.organization_id
          AND gw.academic_year_id = NEW.academic_year_id
          AND gw.grade_level_id = NEW.grade_level_id
          AND gw.wing_id = NEW.wing_id
    ) THEN
        RAISE EXCEPTION USING
            ERRCODE = '23514',
            CONSTRAINT = 'chk_timetable_schedule_assignment_grade_wing',
            MESSAGE = 'Grade bell-schedule override must use the grade timetable wing';
    END IF;
    RETURN NEW;
END $$;

CREATE CONSTRAINT TRIGGER trg_timetable_schedule_assignment_wing
AFTER INSERT OR UPDATE ON timetable_bell_schedule_assignments
DEFERRABLE INITIALLY IMMEDIATE
FOR EACH ROW EXECUTE FUNCTION validate_timetable_schedule_assignment_wing();

CREATE FUNCTION validate_timetable_alternate_eligibility_wing() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.section_id IS NOT NULL AND NEW.wing_id IS NOT NULL AND NOT EXISTS (
        SELECT 1
        FROM sections s
        JOIN timetable_grade_wings gw
          ON gw.organization_id = s.organization_id
         AND gw.academic_year_id = s.academic_year_id
         AND gw.grade_level_id = s.grade_level_id
        WHERE s.id = NEW.section_id
          AND s.organization_id = NEW.organization_id
          AND s.academic_year_id = NEW.academic_year_id
          AND s.grade_level_id = NEW.grade_level_id
          AND gw.wing_id = NEW.wing_id
    ) THEN
        RAISE EXCEPTION USING
            ERRCODE = '23514',
            CONSTRAINT = 'chk_timetable_eligibility_section_wing',
            MESSAGE = 'Alternate teacher eligibility section and wing must agree';
    END IF;
    RETURN NEW;
END $$;

CREATE CONSTRAINT TRIGGER trg_timetable_alternate_eligibility_wing
AFTER INSERT OR UPDATE ON timetable_alternate_teacher_eligibilities
DEFERRABLE INITIALLY IMMEDIATE
FOR EACH ROW EXECUTE FUNCTION validate_timetable_alternate_eligibility_wing();

CREATE FUNCTION validate_timetable_grade_wing_change() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM timetable_bell_schedule_assignments a
        WHERE a.organization_id = NEW.organization_id
          AND a.academic_year_id = NEW.academic_year_id
          AND a.grade_level_id = NEW.grade_level_id
          AND a.wing_id <> NEW.wing_id
    ) THEN
        RAISE EXCEPTION USING
            ERRCODE = '23514',
            CONSTRAINT = 'chk_timetable_grade_wing_schedule_overrides',
            MESSAGE = 'Grade wing cannot change while a bell-schedule override references another wing';
    END IF;
    IF EXISTS (
        SELECT 1 FROM timetable_alternate_teacher_eligibilities e
        WHERE e.organization_id = NEW.organization_id
          AND e.academic_year_id = NEW.academic_year_id
          AND e.grade_level_id = NEW.grade_level_id
          AND e.section_id IS NOT NULL
          AND e.wing_id IS NOT NULL
          AND e.wing_id <> NEW.wing_id
    ) THEN
        RAISE EXCEPTION USING
            ERRCODE = '23514',
            CONSTRAINT = 'chk_timetable_grade_wing_alternate_eligibilities',
            MESSAGE = 'Grade wing cannot change while section-scoped alternate eligibility references another wing';
    END IF;
    RETURN NEW;
END $$;

CREATE CONSTRAINT TRIGGER trg_timetable_grade_wing_change
AFTER UPDATE OF wing_id ON timetable_grade_wings
DEFERRABLE INITIALLY IMMEDIATE
FOR EACH ROW EXECUTE FUNCTION validate_timetable_grade_wing_change();

