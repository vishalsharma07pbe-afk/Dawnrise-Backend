    ),
    -- Timetable configuration uses whole-minute precision.  This makes the
    -- generated minute range below an exact representation rather than a truncation.
    CONSTRAINT chk_timetable_bell_day_minute_granularity CHECK (
        (day_start_time IS NULL OR EXTRACT(SECOND FROM day_start_time) = 0)
        AND (day_end_time IS NULL OR EXTRACT(SECOND FROM day_end_time) = 0)
    ),
