CREATE TABLE timetable_bell_intervals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL CHECK (organization_id > 0),
    bell_schedule_day_id BIGINT NOT NULL CHECK (bell_schedule_day_id > 0),
    interval_type VARCHAR(40) NOT NULL CHECK (interval_type IN (
        'TEACHING','ASSEMBLY','SUPERVISED_ACTIVITY','RECESS','TRANSITION','FIXED_NON_STUDENT'
    )),
    name VARCHAR(120) NOT NULL CHECK (BTRIM(name) <> ''),
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    display_order INTEGER NOT NULL CHECK (display_order > 0),
    coverage_mode VARCHAR(30) NOT NULL CHECK (coverage_mode IN ('NONE','SECTION','SECTION_GROUP','WHOLE_WING')),
    assignee_requirement VARCHAR(40) NOT NULL CHECK (assignee_requirement IN ('NONE','QUALIFIED_SUBJECT_TEACHER','TEACHER_OR_APPROVED_SUPERVISOR')),
    schedulable BOOLEAN NOT NULL,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    start_minute INTEGER GENERATED ALWAYS AS ((EXTRACT(HOUR FROM start_time)::INTEGER * 60) + EXTRACT(MINUTE FROM start_time)::INTEGER) STORED,
    end_minute INTEGER GENERATED ALWAYS AS ((EXTRACT(HOUR FROM end_time)::INTEGER * 60) + EXTRACT(MINUTE FROM end_time)::INTEGER) STORED,
    CONSTRAINT uk_timetable_bell_interval_order UNIQUE (organization_id, bell_schedule_day_id, display_order),
    CONSTRAINT uk_timetable_bell_interval_id_org UNIQUE (id, organization_id),
    CONSTRAINT chk_timetable_bell_interval_times CHECK (end_time > start_time),
    CONSTRAINT chk_timetable_bell_interval_minute_granularity CHECK (
        EXTRACT(SECOND FROM start_time) = 0 AND EXTRACT(SECOND FROM end_time) = 0
    ),
    CONSTRAINT chk_timetable_interval_semantics CHECK (
        (interval_type = 'TEACHING' AND coverage_mode = 'SECTION' AND assignee_requirement = 'QUALIFIED_SUBJECT_TEACHER' AND schedulable)
        OR (interval_type = 'ASSEMBLY' AND coverage_mode IN ('SECTION_GROUP','WHOLE_WING') AND assignee_requirement = 'TEACHER_OR_APPROVED_SUPERVISOR' AND schedulable)
        OR (interval_type = 'SUPERVISED_ACTIVITY' AND coverage_mode IN ('SECTION','SECTION_GROUP') AND assignee_requirement = 'TEACHER_OR_APPROVED_SUPERVISOR' AND schedulable)
        OR (interval_type IN ('RECESS','TRANSITION') AND coverage_mode = 'NONE' AND assignee_requirement = 'NONE' AND NOT schedulable)
        OR (interval_type = 'FIXED_NON_STUDENT' AND coverage_mode = 'NONE' AND assignee_requirement IN ('NONE','TEACHER_OR_APPROVED_SUPERVISOR'))
    ),
    CONSTRAINT fk_timetable_bell_interval_day FOREIGN KEY (bell_schedule_day_id, organization_id)
        REFERENCES timetable_bell_schedule_days (id, organization_id) ON DELETE CASCADE,
    CONSTRAINT ex_timetable_bell_interval_overlap EXCLUDE USING gist (
        organization_id WITH =,
        bell_schedule_day_id WITH =,
        int4range(start_minute, end_minute, '[)') WITH &&
    )
);

