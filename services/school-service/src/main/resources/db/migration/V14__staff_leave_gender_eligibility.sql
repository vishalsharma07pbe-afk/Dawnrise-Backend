ALTER TABLE staff_leave_types
    ADD COLUMN eligibility_gender VARCHAR(12) NOT NULL DEFAULT 'ALL'
        CONSTRAINT chk_staff_leave_policy_gender CHECK (eligibility_gender IN ('ALL','MALE','FEMALE'));

-- Only existing policies with an explicit audience in their name are classified automatically.
UPDATE staff_leave_types SET eligibility_gender='FEMALE'
WHERE UPPER(name) LIKE '%FEMALE ONLY%';
UPDATE staff_leave_types SET eligibility_gender='MALE'
WHERE UPPER(name) LIKE '%MALE ONLY%' AND UPPER(name) NOT LIKE '%FEMALE ONLY%';

CREATE TABLE staff_leave_person_eligibility (
    organization_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
    staff_user_id BIGINT NOT NULL CHECK (staff_user_id > 0),
    eligibility_gender VARCHAR(12) NOT NULL CHECK (eligibility_gender IN ('UNSPECIFIED','MALE','FEMALE')),
    updated_by_user_id BIGINT NOT NULL CHECK (updated_by_user_id > 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (organization_id, staff_user_id)
);

CREATE TABLE staff_leave_person_eligibility_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    staff_user_id BIGINT NOT NULL,
    previous_gender VARCHAR(12) NOT NULL,
    new_gender VARCHAR(12) NOT NULL,
    actor_user_id BIGINT NOT NULL CHECK (actor_user_id > 0),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_staff_leave_eligibility_audit_person
        FOREIGN KEY (organization_id, staff_user_id)
        REFERENCES staff_leave_person_eligibility(organization_id, staff_user_id)
);

CREATE INDEX idx_staff_leave_eligibility_audit_person
    ON staff_leave_person_eligibility_audit(organization_id, staff_user_id, occurred_at DESC);
