CREATE TABLE school_announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
    title VARCHAR(120) NOT NULL CHECK (BTRIM(title)<>'' AND title !~ '[<>]'),
    body VARCHAR(4000) NOT NULL CHECK (BTRIM(body)<>'' AND body !~ '[<>]'),
    severity VARCHAR(12) NOT NULL CHECK (severity IN ('NORMAL','IMPORTANT','URGENT')),
    status VARCHAR(12) NOT NULL CHECK (status IN ('DRAFT','SCHEDULED','PUBLISHED','EXPIRED','CANCELLED')),
    scheduled_at TIMESTAMPTZ,
    published_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    created_by_user_id BIGINT NOT NULL CHECK (created_by_user_id>0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version>=0),
    CONSTRAINT uk_school_announcement_tenant UNIQUE(id,organization_id),
    CONSTRAINT chk_announcement_timing CHECK (expires_at IS NULL OR expires_at>COALESCE(published_at,scheduled_at,created_at))
);

CREATE TABLE school_announcement_audiences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    announcement_id BIGINT NOT NULL,
    audience_type VARCHAR(20) NOT NULL CHECK (audience_type IN
        ('WHOLE_SCHOOL','ROLE','WING','GRADE','SECTION','STAFF','STUDENT','ACTIVE_GUARDIAN')),
    audience_key VARCHAR(80),
    CONSTRAINT fk_school_announcement_audience_tenant FOREIGN KEY(announcement_id,organization_id) REFERENCES school_announcements(id,organization_id) ON DELETE CASCADE,
    CONSTRAINT uk_school_announcement_audience UNIQUE(announcement_id,audience_type,audience_key),
    CONSTRAINT chk_school_announcement_audience_key CHECK (
        (audience_type IN ('WHOLE_SCHOOL','STAFF','STUDENT','ACTIVE_GUARDIAN') AND audience_key IS NULL)
        OR (audience_type IN ('ROLE','WING','GRADE','SECTION') AND BTRIM(audience_key)<>''))
);

CREATE TABLE school_announcement_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    announcement_id BIGINT NOT NULL,
    actor_user_id BIGINT NOT NULL CHECK (actor_user_id>0),
    action VARCHAR(20) NOT NULL CHECK (action IN ('CREATED','UPDATED','SCHEDULED','PUBLISHED','EXPIRED','CANCELLED')),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_school_announcement_audit_tenant FOREIGN KEY(announcement_id,organization_id) REFERENCES school_announcements(id,organization_id) ON DELETE CASCADE
);

CREATE INDEX idx_school_announcements_due ON school_announcements(status,scheduled_at,id)
    WHERE status='SCHEDULED';
CREATE INDEX idx_school_announcements_tenant ON school_announcements(organization_id,created_at DESC,id);

CREATE TABLE dawnrise_releases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL CHECK (BTRIM(title)<>'' AND title !~ '[<>]'),
    summary VARCHAR(500) NOT NULL CHECK (BTRIM(summary)<>'' AND summary !~ '[<>]'),
    details VARCHAR(4000) NOT NULL CHECK (BTRIM(details)<>'' AND details !~ '[<>]'),
    status VARCHAR(12) NOT NULL CHECK (status IN ('DRAFT','SCHEDULED','PUBLISHED','EXPIRED','CANCELLED')),
    scheduled_at TIMESTAMPTZ,
    published_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    created_by_platform_user_id BIGINT NOT NULL CHECK (created_by_platform_user_id>0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version>=0),
    CONSTRAINT chk_release_timing CHECK (expires_at IS NULL OR expires_at>COALESCE(published_at,scheduled_at,created_at))
);

CREATE TABLE dawnrise_release_organizations (
    release_id BIGINT NOT NULL REFERENCES dawnrise_releases(id) ON DELETE CASCADE,
    organization_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
    PRIMARY KEY(release_id,organization_id)
);

CREATE TABLE dawnrise_release_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_id BIGINT NOT NULL REFERENCES dawnrise_releases(id) ON DELETE CASCADE,
    actor_platform_user_id BIGINT NOT NULL CHECK (actor_platform_user_id>0),
    action VARCHAR(20) NOT NULL CHECK (action IN ('CREATED','UPDATED','SCHEDULED','PUBLISHED','EXPIRED','CANCELLED')),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE school_notification_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_type VARCHAR(20) NOT NULL CHECK (source_type IN ('ANNOUNCEMENT','RELEASE')),
    source_id BIGINT NOT NULL CHECK (source_id>0),
    organization_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
    source_event_id VARCHAR(160) NOT NULL,
    event_type VARCHAR(60) NOT NULL CHECK (event_type IN ('SCHOOL_ANNOUNCEMENT','DAWNRISE_RELEASE')),
    importance VARCHAR(20) NOT NULL CHECK (importance IN ('NORMAL','IMPORTANT','URGENT')),
    heading VARCHAR(160) NOT NULL CHECK (BTRIM(heading)<>'' AND heading !~ '[<>]'),
    context VARCHAR(500) NOT NULL CHECK (BTRIM(context)<>'' AND context !~ '[<>]'),
    audience_spec JSONB NOT NULL CHECK (JSONB_TYPEOF(audience_spec)='array'),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','PUBLISHED','DEAD_LETTER','CANCELLED')),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count>=0),
    available_at TIMESTAMPTZ NOT NULL,
    lease_owner UUID,
    lease_until TIMESTAMPTZ,
    published_at TIMESTAMPTZ,
    dead_lettered_at TIMESTAMPTZ,
    last_error VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_school_notification_source UNIQUE(source_type,source_id,organization_id),
    CONSTRAINT uk_school_notification_event UNIQUE(organization_id,source_event_id),
    CONSTRAINT chk_school_notification_lease CHECK ((lease_owner IS NULL)=(lease_until IS NULL))
);
CREATE INDEX idx_school_notification_claim ON school_notification_outbox(status,available_at,lease_until,id)
    WHERE status='PENDING';
CREATE INDEX idx_dawnrise_releases_due ON dawnrise_releases(status,scheduled_at,id)
    WHERE status='SCHEDULED';
