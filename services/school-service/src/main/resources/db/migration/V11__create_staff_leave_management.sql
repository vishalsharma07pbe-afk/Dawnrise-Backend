CREATE TABLE staff_leave_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
    code VARCHAR(40) NOT NULL CHECK (code ~ '^[A-Z][A-Z0-9_]{1,39}$'),
    name VARCHAR(100) NOT NULL CHECK (BTRIM(name)<>''),
    active_from DATE NOT NULL,
    active_to DATE,
    yearly_allowance NUMERIC(7,2) NOT NULL DEFAULT 0 CHECK (yearly_allowance>=0),
    carry_forward_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    carry_forward_limit NUMERIC(7,2) CHECK (carry_forward_limit IS NULL OR carry_forward_limit>=0),
    maximum_consecutive_days NUMERIC(7,2) CHECK (maximum_consecutive_days IS NULL OR maximum_consecutive_days>0),
    supporting_document_required BOOLEAN NOT NULL DEFAULT FALSE,
    paid BOOLEAN NOT NULL DEFAULT TRUE,
    partial_time_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    negative_balance_allowed BOOLEAN NOT NULL DEFAULT FALSE,
    applicable_roles TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    created_by_user_id BIGINT NOT NULL CHECK (created_by_user_id>0),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version>=0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_staff_leave_type_tenant UNIQUE(id,organization_id),
    CONSTRAINT uk_staff_leave_type_code UNIQUE(organization_id,code),
    CONSTRAINT chk_staff_leave_type_dates CHECK(active_to IS NULL OR active_to>=active_from)
);

CREATE TABLE staff_leave_balances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
    staff_user_id BIGINT NOT NULL CHECK(staff_user_id>0),
    leave_type_id BIGINT NOT NULL,
    leave_year INTEGER NOT NULL CHECK(leave_year BETWEEN 2000 AND 2200),
    opening NUMERIC(7,2) NOT NULL DEFAULT 0,
    accrued NUMERIC(7,2) NOT NULL DEFAULT 0,
    carried NUMERIC(7,2) NOT NULL DEFAULT 0,
    used NUMERIC(7,2) NOT NULL DEFAULT 0 CHECK(used>=0),
    pending NUMERIC(7,2) NOT NULL DEFAULT 0 CHECK(pending>=0),
    adjusted NUMERIC(7,2) NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_staff_leave_balance_type FOREIGN KEY(leave_type_id,organization_id) REFERENCES staff_leave_types(id,organization_id),
    CONSTRAINT uk_staff_leave_balance UNIQUE(organization_id,staff_user_id,leave_type_id,leave_year)
);

CREATE TABLE staff_leave_approval_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
    requester_role VARCHAR(50) NOT NULL,
    step_number INTEGER NOT NULL CHECK(step_number>0),
    approver_role VARCHAR(50) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_staff_leave_approval_rule UNIQUE(organization_id,requester_role,step_number),
    CONSTRAINT chk_staff_leave_approval_no_same_role CHECK(requester_role<>approver_role)
);

CREATE TABLE staff_leave_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
    requester_user_id BIGINT NOT NULL CHECK(requester_user_id>0),
    leave_type_id BIGINT NOT NULL,
    request_kind VARCHAR(20) NOT NULL CHECK(request_kind IN ('FULL_DAY','DATE_RANGE','HALF_DAY','LATE_ARRIVAL','EARLY_DEPARTURE','PARTIAL_TIME')),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    start_time TIME,
    end_time TIME,
    half_day_period VARCHAR(10) CHECK(half_day_period IS NULL OR half_day_period IN ('MORNING','AFTERNOON')),
    units NUMERIC(7,2) NOT NULL CHECK(units>0),
    reason VARCHAR(2000) NOT NULL CHECK(BTRIM(reason)<>''),
    document_name VARCHAR(200),
    document_content_type VARCHAR(100),
    document_reference VARCHAR(500),
    status VARCHAR(24) NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','PENDING','APPROVED','REJECTED','WITHDRAWN','CANCELLED','PARTIALLY_CANCELLED')),
    current_approval_step INTEGER NOT NULL DEFAULT 0 CHECK(current_approval_step>=0),
    submitted_at TIMESTAMPTZ,
    decided_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_staff_leave_request_type FOREIGN KEY(leave_type_id,organization_id) REFERENCES staff_leave_types(id,organization_id),
    CONSTRAINT uk_staff_leave_request_tenant UNIQUE(id,organization_id),
    CONSTRAINT chk_staff_leave_request_dates CHECK(end_date>=start_date),
    CONSTRAINT chk_staff_leave_request_times CHECK((start_time IS NULL AND end_time IS NULL) OR (start_time IS NOT NULL AND end_time IS NOT NULL AND end_time>start_time))
);

CREATE TABLE staff_leave_approvals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    leave_request_id BIGINT NOT NULL,
    step_number INTEGER NOT NULL CHECK(step_number>0),
    approver_role VARCHAR(50) NOT NULL,
    approver_user_id BIGINT,
    status VARCHAR(16) NOT NULL DEFAULT 'WAITING' CHECK(status IN ('WAITING','PENDING','APPROVED','REJECTED','CANCELLED')),
    reason VARCHAR(1000),
    decided_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_staff_leave_approval_request FOREIGN KEY(leave_request_id,organization_id) REFERENCES staff_leave_requests(id,organization_id) ON DELETE CASCADE,
    CONSTRAINT uk_staff_leave_approval_step UNIQUE(leave_request_id,step_number)
);

CREATE TABLE staff_leave_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    leave_request_id BIGINT NOT NULL,
    actor_user_id BIGINT NOT NULL CHECK(actor_user_id>0),
    action VARCHAR(30) NOT NULL,
    reason VARCHAR(1000),
    snapshot JSONB NOT NULL DEFAULT '{}'::JSONB,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_staff_leave_audit_request FOREIGN KEY(leave_request_id,organization_id) REFERENCES staff_leave_requests(id,organization_id)
);

CREATE TABLE staff_leave_balance_adjustments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
    balance_id BIGINT NOT NULL REFERENCES staff_leave_balances(id),
    amount NUMERIC(7,2) NOT NULL CHECK(amount<>0),
    reason VARCHAR(1000) NOT NULL CHECK(BTRIM(reason)<>''),
    actor_user_id BIGINT NOT NULL CHECK(actor_user_id>0),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE staff_leave_policy_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
    leave_type_id BIGINT NOT NULL,
    actor_user_id BIGINT NOT NULL CHECK(actor_user_id>0),
    action VARCHAR(20) NOT NULL CHECK(action IN ('CREATED','UPDATED')),
    snapshot JSONB NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_staff_leave_policy_audit_type FOREIGN KEY(leave_type_id,organization_id) REFERENCES staff_leave_types(id,organization_id)
);

CREATE TABLE staff_leave_coverage_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
    leave_request_id BIGINT NOT NULL,
    operation VARCHAR(16) NOT NULL CHECK(operation IN ('UPSERT','CANCEL')),
    source_event_id VARCHAR(180) NOT NULL,
    actor_user_id BIGINT NOT NULL CHECK(actor_user_id>0),
    payload JSONB NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','PUBLISHED','DEAD_LETTER')),
    attempt_count INTEGER NOT NULL DEFAULT 0,
    available_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lease_owner UUID,
    lease_until TIMESTAMPTZ,
    published_at TIMESTAMPTZ,
    dead_lettered_at TIMESTAMPTZ,
    last_error VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_staff_leave_coverage_request FOREIGN KEY(leave_request_id,organization_id) REFERENCES staff_leave_requests(id,organization_id),
    CONSTRAINT uk_staff_leave_coverage_event UNIQUE(organization_id,source_event_id),
    CONSTRAINT chk_staff_leave_coverage_lease CHECK((lease_owner IS NULL)=(lease_until IS NULL))
);

CREATE TABLE staff_leave_coverage_delivery_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
    outbox_id BIGINT NOT NULL REFERENCES staff_leave_coverage_outbox(id),
    action VARCHAR(20) NOT NULL CHECK(action IN ('PUBLISHED','FAILED','DEAD_LETTERED','REQUEUED')),
    actor_user_id BIGINT,
    detail VARCHAR(1000),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

