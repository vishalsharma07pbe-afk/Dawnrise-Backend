CREATE INDEX idx_staff_leave_request_self ON staff_leave_requests(organization_id,requester_user_id,created_at DESC);
CREATE INDEX idx_staff_leave_request_queue ON staff_leave_requests(organization_id,status,updated_at DESC);
CREATE INDEX idx_staff_leave_approval_queue ON staff_leave_approvals(organization_id,status,approver_user_id,approver_role);
CREATE INDEX idx_staff_leave_calendar ON staff_leave_requests(organization_id,start_date,end_date) WHERE status IN ('APPROVED','PARTIALLY_CANCELLED');
