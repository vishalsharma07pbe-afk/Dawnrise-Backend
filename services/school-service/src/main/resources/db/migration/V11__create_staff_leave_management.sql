CREATE FUNCTION prevent_staff_leave_audit_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Staff leave audit records are immutable'; END; $$;
CREATE TRIGGER trg_staff_leave_audit_immutable BEFORE UPDATE OR DELETE ON staff_leave_audit FOR EACH ROW EXECUTE FUNCTION prevent_staff_leave_audit_mutation();
CREATE TRIGGER trg_staff_leave_balance_adjustment_immutable BEFORE UPDATE OR DELETE ON staff_leave_balance_adjustments FOR EACH ROW EXECUTE FUNCTION prevent_staff_leave_audit_mutation();
CREATE TRIGGER trg_staff_leave_policy_audit_immutable BEFORE UPDATE OR DELETE ON staff_leave_policy_audit FOR EACH ROW EXECUTE FUNCTION prevent_staff_leave_audit_mutation();
CREATE TRIGGER trg_staff_leave_delivery_audit_immutable BEFORE UPDATE OR DELETE ON staff_leave_coverage_delivery_audit FOR EACH ROW EXECUTE FUNCTION prevent_staff_leave_audit_mutation();
